#Suma y resta (+ y -)
suma = 12 + 8
resta = 12 - 2

#Multiplicacion y división (* y / ) 
multi = 12 * 5
division = 12 / 5 #devuelve un dato float (Flotante)

#potenciación (Exponente) (**)
exponente = 12**5

#Division baja (//)
division_Baja = 12 // 5  #devuelve un entero redondeado hacia abajo 

#Modulo o Resto
resto = 12 % 5

print(suma)
print(resta)
print(multi)
print(division)
print(exponente)
print(division_Baja)
print(resto)

Tipo_De_Suma= type (suma) #typ(dato) nos devuelve que tipo de dato es.
Tipo_de_Resta = type (resta)
Tipo_de_Multi = type (multi)
tipo_de_division = type (division)
tipo_de_exponente = type (exponente)
tipo_De_division_baja = type(division_Baja)
tipo_de_resto = type(resto)

print (Tipo_De_Suma)
print (Tipo_de_Resta)
print (Tipo_de_Multi)
print(tipo_de_division)
print(tipo_de_exponente)
